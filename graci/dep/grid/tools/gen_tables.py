#!/usr/bin/env python
"""
gen_tables.py: writes the data modules of libgrid from the installed PySCF

  src/data/grid_tables.f90       Bragg radii (bohr), SG-1 radii, Treutler
                                 xi factors, RAD_GRIDS / ANG_ORDER level
                                 tables, Lebedev order -> size map
  src/data/grid_lebedev_tab.f90  Lebedev-Laikov orbit tables (code, a, b, v)
                                 parsed from pyscf/lib/dft/CxLebedevGrid.c

Run once (and whenever PySCF's tables change):
  python tools/gen_tables.py
"""
import os
import re
import sys
import numpy as np
import pyscf
from pyscf.dft import radi, gen_grid
from pyscf.dft.LebedevGrid import LEBEDEV_ORDER
from pyscf.data import radii

here = os.path.dirname(os.path.abspath(__file__))
dest = os.path.join(here, '..', 'src', 'data')

def fmt(x):
    return repr(float(x)) + '_dp'

def int_array(name, vals, per_line=16):
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append('       ' + ', '.join(str(int(v)) for v in vals[i:i+per_line]))
    body = ', &\n'.join(lines)
    return ('  integer(is), parameter :: %s(%d) = [ &\n%s ]\n' % (name, len(vals), body))

def real_array(name, vals, per_line=4, literal=False):
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append('       ' + ', '.join((v + '_dp') if literal else fmt(v) for v in vals[i:i+per_line]))
    body = ', &\n'.join(lines)
    return ('  real(dp), parameter :: %s(%d) = [ &\n%s ]\n' % (name, len(vals), body))

# ---------------------------------------------------------------------
# radii, xi, level tables
# ---------------------------------------------------------------------
bragg = radii.BRAGG                      # bohr, index = Z (0 = ghost)
sg1 = radi.SG1RADII                      # bohr, Z <= 18
xi = radi._treutler_ahlrichs_xi          # Z <= 103
rad_grids = gen_grid.RAD_GRIDS           # (level 0..9, period 1..7)
ang_order = gen_grid.ANG_ORDER
orders = list(LEBEDEV_ORDER.keys())
sizes = list(LEBEDEV_ORDER.values())

with open(os.path.join(dest, 'grid_tables.f90'), 'w') as f:
    f.write('!**********************************************************************\n')
    f.write('! grid_tables: GENERATED by tools/gen_tables.py from PySCF %s\n' % pyscf.__version__)
    f.write('! Bragg radii (bohr, index Z, 0 = ghost), SG-1 radii (bohr), Treutler\n')
    f.write('! xi factors, RAD_GRIDS / ANG_ORDER level tables and the Lebedev\n')
    f.write('! order -> size map. Do not edit by hand.\n')
    f.write('!**********************************************************************\n')
    f.write('module grid_tables\n\n  use grid_constants\n\n  implicit none\n\n')
    f.write('  integer(is), parameter :: zmax_bragg = %d, zmax_sg1 = %d, zmax_xi = %d\n' %
            (len(bragg)-1, len(sg1)-1, len(xi)-1))
    f.write(real_array('bragg_radii', bragg))
    f.write(real_array('sg1_radii', sg1))
    f.write(real_array('treutler_xi', xi))
    f.write('  ! upper nuclear charges of the periods (period = count(Z > period_zmax) + 1)\n')
    f.write(int_array('period_zmax', [2, 10, 18, 36, 54, 86, 118]))
    f.write('  ! rad_grids(level, period) and ang_order(level, period), level 0..9, period 1..7\n')
    f.write('  integer(is), parameter :: rad_grids_t(70) = [ &\n')
    f.write(', &\n'.join('       ' + ', '.join(str(int(v)) for v in row) for row in rad_grids) + ' ]\n')
    f.write('  integer(is), parameter :: ang_order_t(70) = [ &\n')
    f.write(', &\n'.join('       ' + ', '.join(str(int(v)) for v in row) for row in ang_order) + ' ]\n')
    f.write('  integer(is), parameter :: rad_grids(0:9,7) = reshape(rad_grids_t, [10, 7], order=[2, 1])\n')
    f.write('  integer(is), parameter :: ang_order(0:9,7) = reshape(ang_order_t, [10, 7], order=[2, 1])\n')
    f.write('  ! Lebedev orders and sizes\n')
    f.write('  integer(is), parameter :: nleb = %d\n' % len(sizes))
    f.write(int_array('leb_orders', orders))
    f.write(int_array('leb_sizes', sizes))
    f.write('\nend module grid_tables\n')

# ---------------------------------------------------------------------
# Lebedev orbits
# ---------------------------------------------------------------------
csrc = os.path.join(os.path.dirname(pyscf.__file__), 'lib', 'dft', 'CxLebedevGrid.c')
if not os.path.isfile(csrc):
    sys.exit('CxLebedevGrid.c not found: ' + csrc)
text = open(csrc).read()
fun_re = re.compile(r'static int MakeAngularGrid_(\d+)\(double \(\*pOut\)\[4\]\)\s*\{(.*?)\n\}', re.S)
assign_re = re.compile(r'\b([abv])\s*=\s*([-+]?[0-9.]+(?:[eE][-+]?\d+)?)\s*;')
call_re = re.compile(r'SphGenOh\(&pOut\[N\]\[0\],\s*(\d),\s*a,\s*b,\s*v\)')
orbits = {}
for m in fun_re.finditer(text):
    n = int(m.group(1))
    body = m.group(2)
    cur = {'a': '0.0', 'b': '0.0', 'v': '0.0'}
    orb = []
    # walk statements in order
    for stmt in re.finditer(r'(\b[abv]\s*=\s*[-+]?[0-9.]+(?:[eE][-+]?\d+)?\s*;)|(SphGenOh\(&pOut\[N\]\[0\],\s*\d,\s*a,\s*b,\s*v\))', body):
        if stmt.group(1):
            am = assign_re.match(stmt.group(1))
            cur[am.group(1)] = am.group(2)
        else:
            cm = call_re.match(stmt.group(2))
            orb.append((int(cm.group(1)), cur['a'], cur['b'], cur['v']))
    orbits[n] = orb
npts_of_code = {0: 6, 1: 12, 2: 8, 3: 24, 4: 24, 5: 48}
for n in sizes[1:]:
    if n not in orbits:
        sys.exit('no orbit table for Lebedev size %d' % n)
    tot = sum(npts_of_code[c] for c, a, b, v in orbits[n])
    if tot != n:
        sys.exit('Lebedev size %d: orbits give %d points' % (n, tot))

codes, aa, bb, vv, orb0 = [], [], [], [], [1]
for n in sizes:
    if n == 1:
        orb0.append(orb0[-1])
        continue
    for c, a, b, v in orbits[n]:
        codes.append(c); aa.append(a); bb.append(b); vv.append(v)
    orb0.append(len(codes) + 1)
norb = len(codes)

def c2f(lit):
    s = lit.lower()
    if 'e' not in s:
        s += 'e0'
    return s

with open(os.path.join(dest, 'grid_lebedev_tab.f90'), 'w') as f:
    f.write('!**********************************************************************\n')
    f.write('! grid_lebedev_tab: GENERATED by tools/gen_tables.py from PySCF %s\n' % pyscf.__version__)
    f.write('! (pyscf/lib/dft/CxLebedevGrid.c, Lebedev-Laikov orbit tables as\n')
    f.write('! converted by C. van Wuellen and G. Knizia). Orbit io of size\n')
    f.write('! leb_sizes(k) has code leb_code(io), parameters leb_a, leb_b and\n')
    f.write('! weight leb_v, io = leb_orb0(k) .. leb_orb0(k+1)-1. Do not edit.\n')
    f.write('! Users of these grids are asked to cite V.I. Lebedev and D.N. Laikov,\n')
    f.write('! Doklady Mathematics 59, 477 (1999).\n')
    f.write('!**********************************************************************\n')
    f.write('module grid_lebedev_tab\n\n  use grid_constants\n\n  implicit none\n\n')
    f.write('  integer(is), parameter :: norb_leb = %d\n' % norb)
    f.write(int_array('leb_orb0', orb0))
    f.write(int_array('leb_code', codes, per_line=24))
    f.write(real_array('leb_a', [c2f(x) for x in aa], per_line=6, literal=True))
    f.write(real_array('leb_b', [c2f(x) for x in bb], per_line=6, literal=True))
    f.write(real_array('leb_v', [c2f(x) for x in vv], per_line=6, literal=True))
    f.write('\nend module grid_lebedev_tab\n')

print('wrote grid_tables.f90 (bragg %d, sg1 %d, xi %d) and grid_lebedev_tab.f90 (%d orbits, %d sizes)'
      % (len(bragg), len(sg1), len(xi), norb, len(sizes)))
